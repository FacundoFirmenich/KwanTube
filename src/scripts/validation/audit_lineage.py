# ---------------------------------------------------------------------------
# Core comparison
# ---------------------------------------------------------------------------

def _collect_files(root: Path, bases: list[str]) -> dict[Path, str]:
    """Collect {relative_path: sha256} for all non-excluded files under base dirs."""
    result: dict[Path, str] = {}
    for base in bases:
        candidate = root / base
        if candidate.exists():
            for path in candidate.rglob("*"):
                if not path.is_file():
                    continue
                rel = path.relative_to(root)
                if _is_excluded(rel):
                    continue
                result[rel] = sha256(path)
    return result


def compare_trees(
    current_root: Path,
    backup_root: Path,
    bases: list[str],
) -> list[FileLineage]:
    """Compare current and backup trees under the given base directories."""

    current_files: dict[Path, str] = _collect_files(current_root, bases)
    backup_files:  dict[Path, str] = _collect_files(backup_root,  bases)

    # Reverse-index: sha256 → paths in current tree (enables relocation detection)
    current_sha_to_paths: dict[str, list[str]] = {}
    for rel, digest in current_files.items():
        current_sha_to_paths.setdefault(digest, []).append(
            str(rel).replace("\\", "/")
        )

    records: list[FileLineage] = []
    all_rels: set[Path] = set(current_files) | set(backup_files)

    for rel in sorted(all_rels):
        cur_sha = current_files.get(rel)
        bak_sha = backup_files.get(rel)
        rel_str = str(rel).replace("\\", "/")

        cur_exists = cur_sha is not None
        bak_exists = bak_sha is not None

        if cur_exists and bak_exists:
            status = "SAME" if cur_sha == bak_sha else "UPDATED"
            target = None

        elif cur_exists and not bak_exists:
            status = "ADDED"
            target = None

        elif bak_exists and not cur_exists:
            # Check: same content at a different path in current tree?
            other_paths = [
                p for p in current_sha_to_paths.get(bak_sha, [])
                if p != rel_str
            ]
            if other_paths:
                status = "RELOCATED"
                target = other_paths[0]
            elif rel_str in _V3_5_1_KNOWN_EVOLUTION:
                # Documented v3.5.1 evolution — not an unexpected deletion
                status = "DEPRECATED_INTENTIONAL"
                target = None
            else:
                # Genuinely missing with no explanation → needs manual review
                status = "REMOVED"
                target = None

        else:
            status = "ABSENT"
            target = None

        records.append(FileLineage(
            path=rel_str,
            current_exists=cur_exists,
            backup_exists=bak_exists,
            current_sha256=cur_sha,
            backup_sha256=bak_sha,
            status=status,
            relocation_target=target,
        ))

    return records


# ---------------------------------------------------------------------------
# Output formatting
# ---------------------------------------------------------------------------

_SEPARATOR = "─" * 62


def _build_verdict(counts: dict[str, int]) -> str:
    """Derive a one-line verdict from status counts.

    VERDICT: CLEAN  — no unexplained removals (REMOVED == 0).
    VERDICT: REVIEW_REQUIRED — at least one REMOVED file has no SHA-256 match
             and is not in the known-evolution allowlist.
    """
    removed    = counts.get("REMOVED", 0)
    updated    = counts.get("UPDATED", 0)
    added      = counts.get("ADDED", 0)
    reloc      = counts.get("RELOCATED", 0)
    deprecated = counts.get("DEPRECATED_INTENTIONAL", 0)
    same       = counts.get("SAME", 0)

    if removed == 0 and updated == 0 and added == 0 and reloc == 0 and deprecated == 0:
        return "IDENTICAL — current tree matches baseline exactly."

    if removed == 0:
        parts = []
        if same:       parts.append(f"{same} identical")
        if updated:    parts.append(f"{updated} updated (v3.5.1 evolution)")
        if added:      parts.append(f"{added} added")
        if reloc:      parts.append(f"{reloc} relocated")
        if deprecated: parts.append(f"{deprecated} deprecated/reorganised (documented)")
        return "CLEAN — " + "; ".join(parts) + ". No unexpected deletions."

    return (
        f"REVIEW_REQUIRED — {removed} file(s) absent from current tree without "
        f"SHA-256 match and not in known-evolution allowlist. "
        f"Manual verification required."
    )


def _print_summary(records: list[FileLineage], backup_path: Path, out_json: Path) -> None:
    """Print a clean, categorised summary to stdout."""

    counts: dict[str, int] = {}
    for r in records:
        counts[r.status] = counts.get(r.status, 0) + 1

    print(f"[audit_lineage] Baseline : {backup_path.name}")
    print(f"[audit_lineage] Compared (excl. __pycache__): {len(records)} files")
    print(f"[audit_lineage] {_SEPARATOR}")

    order = ["SAME", "UPDATED", "RELOCATED", "ADDED", "DEPRECATED_INTENTIONAL", "REMOVED"]
    labels = {
        "SAME":                  "SAME                    (identical to baseline)",
        "UPDATED":               "UPDATED                 (v3.5.1 legitimate evolution)",
        "RELOCATED":             "RELOCATED               (same content, reorganised path)",
        "ADDED":                 "ADDED                   (new modules / tooling)",
        "DEPRECATED_INTENTIONAL":"DEPRECATED_INTENTIONAL  (documented in v3.5.1 release)",
        "REMOVED":               "REMOVED ✗               (no SHA-256 match — verify)",
    }
    for status in order:
        n = counts.get(status, 0)
        if n > 0:
            print(f"[audit_lineage]   {labels[status]:56s}: {n:3d}")

    verdict = _build_verdict(counts)
    print(f"[audit_lineage] {_SEPARATOR}")
    print(f"[audit_lineage] VERDICT  : {verdict}")
    print(f"[audit_lineage] {_SEPARATOR}")

    # Only list truly unexpected removals (not deprecated ones)
    truly_removed = [r for r in records if r.status == "REMOVED"]
    if truly_removed:
        print("[audit_lineage] Files requiring manual review:")
        for r in truly_removed:
            print(f"[audit_lineage]   ✗ {r.path}")

    print(f"[audit_lineage] wrote {out_json}")


# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------

def main() -> int:
    """Run a read-only lineage comparison and emit JSON report."""

    script_root    = Path(__file__).resolve().parents[3]   # KwanTube/
    workspace_root = script_root.parent

    parser = argparse.ArgumentParser(
        description="Audit current repo against stable backup (read-only)",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument(
        "--current", type=Path, default=script_root,
        help="Root of the current repository.",
    )
    parser.add_argument(
        "--backup", type=Path,
        default=workspace_root / "KwanTube_repo_backup_estable_28042026",
        help="Root of the stable baseline directory.",
    )
    parser.add_argument(
        "--out-json", type=Path,
        default=script_root / "outputs_data" / "raw_json" / "audit" / "lineage_audit.json",
        help="Destination for the JSON audit ledger.",
    )
    parser.add_argument(
        "--paths", nargs="*", default=["src/qmc_mt", "src/scripts"],
        help="Subdirectory paths to audit (relative to both roots).",
    )
    args = parser.parse_args()

    if not args.backup.exists():
        print(
            f"[audit_lineage] WARNING: backup directory not found: {args.backup}\n"
            f"[audit_lineage] Single-tree mode (all files classified as ADDED).",
            file=sys.stderr,
        )

    records = compare_trees(args.current, args.backup, args.paths)

    args.out_json.parent.mkdir(parents=True, exist_ok=True)
    args.out_json.write_text(
        json.dumps([asdict(r) for r in records], indent=2), encoding="utf-8"
    )

    _print_summary(records, args.backup, args.out_json)
    return 0


