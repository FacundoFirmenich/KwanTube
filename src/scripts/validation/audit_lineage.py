"""Forensic lineage audit for local KwanTube files.

This script compares the current local repository tree against an optional
stable backup tree. It is intentionally read-only: it never modifies files and
never interacts with Git remotes.

Classification of delta entries (v3.5.1 semantics):
  SAME                   — file present in both trees with identical SHA-256.
  UPDATED                — file present in both trees but with different SHA-256
                           (legitimate code evolution since backup was taken).
  ADDED                  — file present only in current tree and not a relocation
                           (new module or new auxiliary tool).
  RELOCATED              — file absent from its old path but whose SHA-256 content
                           is present elsewhere in the current tree.
  DEPRECATED_INTENTIONAL — file absent from current tree, documented in the
                           v3.5.1 release notes as intentionally removed or
                           superseded. Does NOT trigger REVIEW_REQUIRED.
  REMOVED                — file truly absent from current tree with no SHA-256 match
                           and not in the known-evolution allowlist. Triggers review.

Generated files (*.pyc, __pycache__/) are always excluded: they are
auto-generated by the Python interpreter and carry no scientific content.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from dataclasses import asdict, dataclass
from pathlib import Path


# ---------------------------------------------------------------------------
# SHA-256 utilities
# ---------------------------------------------------------------------------

def sha256(path: Path) -> str:
    """Compute SHA-256 digest for a file."""
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1_048_576), b""):
            h.update(chunk)
    return h.hexdigest()


# ---------------------------------------------------------------------------
# Data model
# ---------------------------------------------------------------------------

@dataclass(frozen=True)
class FileLineage:
    """Comparison record for one relative path."""

    path: str
    current_exists: bool
    backup_exists: bool
    current_sha256: str | None
    backup_sha256: str | None
    status: str
    relocation_target: str | None = None


# ---------------------------------------------------------------------------
# Exclusion filter — auto-generated files carry no scientific content
# ---------------------------------------------------------------------------

_EXCLUDED_NAMES: frozenset[str] = frozenset({"__pycache__"})
_EXCLUDED_SUFFIXES: frozenset[str] = frozenset({".pyc", ".pyo"})


def _is_excluded(rel: Path) -> bool:
    """Return True for auto-generated files."""
    parts = rel.parts
    if any(p in _EXCLUDED_NAMES for p in parts):
        return True
    if rel.suffix in _EXCLUDED_SUFFIXES:
        return True
    return False


